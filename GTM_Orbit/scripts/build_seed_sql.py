"""Builds snowflake/04_seed_data.sql: INSERT statements for every seed CSV, so the
seed data can be loaded from a Snowsight worksheet (no local Python needed)."""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED = os.path.join(ROOT, "snowflake", "seed")
TABLES = [
    ("demo_accounts.csv", "GTM_DEMO.APP.DEMO_ACCOUNTS", {}),
    ("sequences.csv", "GTM_DEMO.APP.SEQUENCES", {}),
    ("gong_calls.csv", "GTM_DEMO.RAW_GONG.CALLS", {}),
    ("gong_call_participants.csv", "GTM_DEMO.RAW_GONG.CALL_PARTICIPANTS", {}),
    ("gong_transcript_utterances.csv", "GTM_DEMO.RAW_GONG.TRANSCRIPT_UTTERANCES", {}),
    ("gong_tracker_hits.csv", "GTM_DEMO.RAW_GONG.TRACKER_HITS", {}),
    ("product_usage_monthly.csv", "GTM_DEMO.SIGNALS.PRODUCT_USAGE_MONTHLY", {}),
    ("intent_signals_weekly.csv", "GTM_DEMO.SIGNALS.INTENT_SIGNALS_WEEKLY", {}),
    ("critical_events.csv", "GTM_DEMO.SIGNALS.CRITICAL_EVENTS", {}),
    ("priority_scores.csv", "GTM_DEMO.SCORING.PRIORITY_SCORES", {"FEATURE_STATUS": "PARSE_JSON({})"}),
    ("growth_vector.csv", "GTM_DEMO.SCORING.GROWTH_VECTOR", {}),
]
def q(v):
    return "NULL" if v == "" else "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"
out = ["-- GTM AI demo · 04 seed data (generated by scripts/build_seed_sql.py). Safe to re-run.",
       "USE ROLE ACCOUNTADMIN;", "USE WAREHOUSE GTM_DEMO_WH;", ""]
for fname, table, wrap in TABLES:
    rows = list(csv.reader(open(os.path.join(SEED, fname), newline="")))
    hdr, data = rows[0], rows[1:]
    out.append(f"TRUNCATE TABLE {table};")
    vals = []
    for r in data:
        cells = [wrap.get(h, "{}").format(q(v)) for h, v in zip(hdr, r)]
        vals.append("(" + ", ".join(cells) + ")")
    if any(wrap.values()):
        # PARSE_JSON is not allowed inside VALUES, so use INSERT ... SELECT ... UNION ALL
        sel = "\nUNION ALL ".join("SELECT " + v[1:-1] for v in vals)
        out.append(f"INSERT INTO {table} ({', '.join(hdr)})\n{sel};")
    else:
        out.append(f"INSERT INTO {table} ({', '.join(hdr)}) VALUES\n" + ",\n".join(vals) + ";")
    out.append("")
path = os.path.join(ROOT, "snowflake", "04_seed_data.sql")
open(path, "w").write("\n".join(out))
print(path, os.path.getsize(path))
